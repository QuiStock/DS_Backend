CREATE OR REPLACE FUNCTION public.prevent_referenced_store_change()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF TG_TABLE_NAME = 'sale' THEN
    IF NEW."store_id" IS DISTINCT FROM OLD."store_id"
       AND EXISTS (SELECT 1 FROM "sale_item" WHERE "sale_id" = OLD."id") THEN
      RAISE EXCEPTION 'Sale store cannot change while referenced by sale items'
        USING ERRCODE = '23514';
    END IF;
  ELSIF TG_TABLE_NAME = 'batch' THEN
    IF (NEW."store_id" IS DISTINCT FROM OLD."store_id"
        OR NEW."product_id" IS DISTINCT FROM OLD."product_id")
       AND (EXISTS (SELECT 1 FROM "sale_item" WHERE "batch_id" = OLD."id")
            OR EXISTS (SELECT 1 FROM "inventory_movement" WHERE "batch_id" = OLD."id")) THEN
      RAISE EXCEPTION 'Batch product/store cannot change while referenced by transactions'
        USING ERRCODE = '23514';
    END IF;
  END IF;
  RETURN NEW;
END; $$;

