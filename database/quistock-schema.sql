CREATE OR REPLACE FUNCTION public.check_local_user_store_scope()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  v_user_id BIGINT;
BEGIN
  IF TG_TABLE_NAME = 'user_store' THEN
    IF TG_OP = 'INSERT' THEN
      PERFORM public.assert_local_user_store_scope(NEW."user_id");
    ELSIF TG_OP = 'DELETE' THEN
      PERFORM public.assert_local_user_store_scope(OLD."user_id");
    ELSE
      PERFORM public.assert_local_user_store_scope(OLD."user_id");
      IF NEW."user_id" IS DISTINCT FROM OLD."user_id" THEN
        PERFORM public.assert_local_user_store_scope(NEW."user_id");
      END IF;
    END IF;
  ELSIF TG_TABLE_NAME = 'user_account' THEN
    PERFORM public.assert_local_user_store_scope(NEW."id");
  ELSIF TG_TABLE_NAME = 'store' THEN
    IF NEW."status" IS DISTINCT FROM OLD."status" THEN
      FOR v_user_id IN
        SELECT DISTINCT us."user_id"
        FROM public."user_store" us
        WHERE us."store_id" = NEW."id"
          AND us."active" = TRUE
        ORDER BY us."user_id"
      LOOP
        PERFORM public.assert_local_user_store_scope(v_user_id);
      END LOOP;
    END IF;
  ELSIF TG_TABLE_NAME = 'role' THEN
    IF NEW."code" IS DISTINCT FROM OLD."code" THEN
      FOR v_user_id IN
        SELECT u."id"
        FROM public."user_account" u
        WHERE u."role_id" = NEW."id"
        ORDER BY u."id"
      LOOP
        PERFORM public.assert_local_user_store_scope(v_user_id);
      END LOOP;
    END IF;
  END IF;
  RETURN NULL;
END;
$$;

