  ON "suggestion_decision";

CREATE TRIGGER "trg_suggestion_decision_audit"
AFTER INSERT OR UPDATE OR DELETE
ON "suggestion_decision"
FOR EACH ROW
EXECUTE FUNCTION "capture_audit_event"();

