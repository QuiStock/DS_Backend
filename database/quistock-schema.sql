-- Serialize checks for the same user at transaction end. A local account may be
-- inserted and assigned, or moved between stores, within one transaction.
CREATE OR REPLACE FUNCTION public.assert_local_user_store_scope(p_user_id BIGINT)
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
  v_role_code VARCHAR(50);
  v_user_status TEXT;
  v_active_assignments BIGINT;
  v_active_stores BIGINT;
BEGIN
  PERFORM pg_advisory_xact_lock(
    hashtext('quistock.user_store.scope'),
    hashtext(p_user_id::TEXT)
  );

  SELECT r."code", u."status"::TEXT
    INTO v_role_code, v_user_status
  FROM public."user_account" u
  JOIN public."role" r ON r."id" = u."role_id"
  WHERE u."id" = p_user_id;

  IF NOT FOUND THEN
    RETURN;
  END IF;

  SELECT COUNT(*),
         COUNT(*) FILTER (WHERE s."status" = 'ACTIVE')
    INTO v_active_assignments, v_active_stores
  FROM public."user_store" us
  JOIN public."store" s ON s."id" = us."store_id"
  WHERE us."user_id" = p_user_id
    AND us."active" = TRUE;

  IF v_role_code IN ('EMPLOYEE', 'MANAGER') THEN
    IF v_active_assignments > 1
       OR (v_user_status = 'ACTIVE'
           AND (v_active_assignments <> 1 OR v_active_stores <> 1)) THEN
      RAISE EXCEPTION
        'User % (%) must have exactly one active assignment to an active store when active; inactive users may have at most one',
        p_user_id, v_role_code
        USING ERRCODE = '23514';
    END IF;
  ELSIF v_role_code = 'REGIONAL_MANAGER' AND v_active_assignments <> 0 THEN
    RAISE EXCEPTION
      'Regional manager % must access stores through region_manager_assignment, not user_store',
      p_user_id
