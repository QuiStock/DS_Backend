-- Validates the recipient's active scope when a suggestion notification is written.
-- Access to existing notifications must also be checked when they are read.
CREATE OR REPLACE FUNCTION public.check_notification_suggestion_scope()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE v_store_id BIGINT; v_role_code VARCHAR(50); v_status user_status;
BEGIN
  IF NEW."suggestion_id" IS NULL THEN RETURN NEW; END IF;
  SELECT "store_id" INTO v_store_id FROM public."suggestion_context" WHERE "id" = NEW."suggestion_id";
  IF NOT FOUND THEN RETURN NEW; END IF;
  SELECT r."code", u."status" INTO v_role_code, v_status
  FROM "user_account" u JOIN "role" r ON r."id" = u."role_id"
  WHERE u."id" = NEW."user_id";
  IF v_status IS DISTINCT FROM 'ACTIVE' OR NOT (
    (v_role_code IN ('EMPLOYEE','MANAGER') AND EXISTS (
      SELECT 1 FROM "user_store" us JOIN "store" st ON st."id" = us."store_id"
      WHERE us."user_id" = NEW."user_id" AND us."store_id" = v_store_id
        AND us."active" = TRUE AND st."status" = 'ACTIVE'))
    OR
    (v_role_code = 'REGIONAL_MANAGER' AND EXISTS (
      SELECT 1 FROM "region_manager_assignment" a JOIN "store" st ON st."region_id" = a."region_id"
      WHERE a."user_id" = NEW."user_id" AND st."id" = v_store_id
        AND a."active" = TRUE AND st."status" = 'ACTIVE'))
  ) THEN
    RAISE EXCEPTION 'Notification recipient is not authorized for suggestion store'
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END; $$;

