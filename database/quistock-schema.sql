-- QuiStock PostgreSQL — esquema consolidado v12.
-- Reúne a DDL-base v10, a normalização v11 e a remoção v12 da tabela não utilizada.
-- O arquivo reproduz o estado final em um banco vazio; não o reaplique em 2ano_ds_oficial.
-- A migration v12 remove analysis_login_run sem CASCADE.
-- A seção de normalização v11 preserva os dados tipados e snapshots.
-- Fonte da seção v11: migrations/2026-11-02-v10-to-v11-3fn.sql.
-- QuiStock - PostgreSQL schema, version 10.
-- Normalized transaction references and typed product-analysis attributes.
-- Product/store are derived from batch or from the suggestion source relation.
-- See quistock-v10-cardinalidades.md for explicit relationship cardinalities.
-- Consolidated fresh-install DDL. Backend Flyway V5/V6 still reference role_permission
-- during legacy-role merges; handle that migration path before applying those revisions.
-- Cardinality notes for the v10 normalization:
-- sale (1) -> (0..N) sale_item; each sale_item has exactly one sale and one batch.
-- batch (1) -> (0..N) sale_item; batch and sale_item can each be the source of movements.
-- A sale_item's product comes from batch; the deferred trigger keeps sale and batch stores equal.
-- Each inventory_movement has exactly one source: batch_id XOR sale_item_id. When linked
-- to a sale item, batch/product/store are derived through sale_item.batch_id.
-- A suggestion has exactly one source: product_analysis OR product_store.
-- Each source can support multiple suggestions; product_analysis keeps its per-type uniqueness.
-- origin describes who created the suggestion, not which source FK is populated.
-- See quistock-v10-cardinalidades.md for the complete relationship matrix.
-- Canonical PostgreSQL schema for the QuiStock API.
-- ERP product codes are also used as SKUs and must fit VARCHAR(100).
-- ERP batches provide price; the current price is projected to product_store.
-- Current product/store metrics and sale price are stored in product_store.
-- Permission tables are omitted; API authorization uses role and store/region scope.
-- User passwords stay in SQL; NoSQL auth stores sessions and refresh tokens only.
-- Employees and store managers have exactly one active store when their account is active.
-- Regional managers access stores through their region, not user_store.
-- Store data is read-only in the application; ERP/RPA technical sync may still write it.

