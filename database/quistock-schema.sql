CREATE TABLE "suggestion" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "product_analysis_id" BIGINT,
  "store_id" BIGINT NOT NULL,
  "product_id" BIGINT NOT NULL,
  "type" suggestion_type NOT NULL,
  "origin" suggestion_origin NOT NULL,
  "status" suggestion_status NOT NULL,
  "ml_batch_count" INT,
  "current_batch_count" INT,
  "ml_discount_percentage" NUMERIC(5,2),
  "current_discount_percentage" NUMERIC(5,2),
  "promotion_valid_from" DATE,
  "promotion_valid_until" DATE,
  "reference_sale_price" NUMERIC(12,2),
  "promotional_price" NUMERIC(12,2),
  "available_for_triage" BOOLEAN NOT NULL DEFAULT TRUE,
  "created_by_id" BIGINT,
  "created_at" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updated_at" TIMESTAMPTZ,
  CONSTRAINT "chk_suggestion_batch_counts"
    CHECK (
      (ml_batch_count IS NULL OR ml_batch_count > 0)
      AND (current_batch_count IS NULL OR current_batch_count > 0)
    ),
  CONSTRAINT "chk_suggestion_discounts"
    CHECK (
      (ml_discount_percentage IS NULL OR ml_discount_percentage >= 0 AND ml_discount_percentage <= 100)
      AND (current_discount_percentage IS NULL OR current_discount_percentage >= 0 AND current_discount_percentage <= 100)
    ),
  CONSTRAINT "chk_suggestion_prices"
    CHECK (
      (reference_sale_price IS NULL OR reference_sale_price >= 0)
      AND (promotional_price IS NULL OR promotional_price >= 0)
    ),
  CONSTRAINT "chk_suggestion_type_fields"
    CHECK (
      (
        type = 'ORDER'
        AND ml_discount_percentage IS NULL
        AND current_discount_percentage IS NULL
        AND promotion_valid_from IS NULL
        AND promotion_valid_until IS NULL
        AND reference_sale_price IS NULL
        AND promotional_price IS NULL
      )
      OR
      (
        type = 'PROMOTION'
        AND promotion_valid_from IS NOT NULL
        AND promotion_valid_until IS NOT NULL
        AND promotion_valid_until >= promotion_valid_from
      )
      OR
      (
        type = 'MONITOR'
        AND product_analysis_id IS NOT NULL
        AND origin = 'ML'
        AND status = 'GENERATED'
        AND ml_batch_count IS NULL
        AND current_batch_count IS NULL
        AND ml_discount_percentage IS NULL
        AND current_discount_percentage IS NULL
        AND promotion_valid_from IS NULL
        AND promotion_valid_until IS NULL
        AND reference_sale_price IS NULL
        AND promotional_price IS NULL
        AND available_for_triage = FALSE
      )
    ),
  CONSTRAINT "chk_suggestion_origin_creator"
    CHECK (
      (origin = 'ML' AND created_by_id IS NULL)
      OR
      origin IN ('EMPLOYEE', 'MANAGER')
    )
);

