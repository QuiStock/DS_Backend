-- Auditoria completa de alterações nas tabelas transacionais selecionadas.
-- O campo data preserva NEW, OLD, TG_OP e CURRENT_USER sem alterar o modelo
-- de negócio das entidades auditadas.
CREATE OR REPLACE FUNCTION "capture_audit_event"()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  v_entity_id BIGINT;
  v_user_id BIGINT;
BEGIN
  IF TG_OP = 'DELETE' THEN
    v_entity_id := OLD.id;
  ELSE
    v_entity_id := NEW.id;
  END IF;

  IF TG_TABLE_NAME = 'suggestion' THEN
    IF TG_OP = 'DELETE' THEN
      v_user_id := OLD.created_by_id;
    ELSE
      v_user_id := NEW.created_by_id;
    END IF;
  ELSIF TG_TABLE_NAME = 'suggestion_decision' THEN
    IF TG_OP = 'DELETE' THEN
      v_user_id := OLD.manager_id;
    ELSE
      v_user_id := NEW.manager_id;
    END IF;
  END IF;

  INSERT INTO "audit_event" (
    "user_id",
    "entity",
    "entity_id",
    "action",
    "data",
    "occurred_at"
  )
  VALUES (
    v_user_id,
    TG_TABLE_NAME,
    v_entity_id,
    TG_OP,
    jsonb_build_object(
      'NEW', CASE
        WHEN TG_OP IN ('INSERT', 'UPDATE') THEN to_jsonb(NEW)
        ELSE NULL
      END,
      'OLD', CASE
        WHEN TG_OP IN ('UPDATE', 'DELETE') THEN to_jsonb(OLD)
        ELSE NULL
      END,
      'TG_OP', TG_OP,
      'CURRENT_USER', CURRENT_USER
    ),
    CURRENT_TIMESTAMP
  );

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;

  RETURN NEW;
END;
$$;

